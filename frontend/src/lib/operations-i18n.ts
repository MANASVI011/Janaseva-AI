export function operationLabel(
  language: Language,
  kind: "status" | "stage" | "priority" | "action",
  value: string,
) {
  const dictionary = words[language] as Record<string, string>;
  return (
    dictionary[`${kind}_${value}`] ??
    value
      .replaceAll("_", " ")
      .toLocaleLowerCase(language === "kn" ? "kn-IN" : "en-IN")
  );
}
